from entities.atm import ATM
from entities.account import Account
from entities.card import Card


# --------------------------------------------
# Create Account
# --------------------------------------------

account = Account(
    "ACC001",
    10000
)


# --------------------------------------------
# Create Card
# --------------------------------------------

card = Card(
    "CARD001",
    "1234",
    account
)


# --------------------------------------------
# Create ATM
# --------------------------------------------

atm = ATM(
    cash=50000
)


# --------------------------------------------
# Test 1 — Insert Card
# --------------------------------------------

atm.insert_card(card)


# --------------------------------------------
# Test 2 — Wrong PIN
# --------------------------------------------

try:

    atm.enter_pin("9999")

except ValueError as e:

    print("Error:", e)


# --------------------------------------------
# Test 3 — Correct PIN
# --------------------------------------------

atm.enter_pin("1234")


# --------------------------------------------
# Test 4 — Balance
# --------------------------------------------

atm.check_balance()


# --------------------------------------------
# Test 5 — Withdraw
# --------------------------------------------

atm.withdraw(3000)


# --------------------------------------------
# Test 6 — Balance After Withdrawal
# --------------------------------------------

atm.check_balance()


# --------------------------------------------
# Test 7 — Deposit
# --------------------------------------------

atm.deposit(2000)


# --------------------------------------------
# Test 8 — Balance After Deposit
# --------------------------------------------

atm.check_balance()


# --------------------------------------------
# Test 9 — Eject Card
# --------------------------------------------

atm.eject_card()


# --------------------------------------------
# Test 10 — Transaction Without Card
# --------------------------------------------

try:

    atm.withdraw(1000)

except ValueError as e:

    print("Error:", e)